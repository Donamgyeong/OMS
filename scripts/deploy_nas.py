#!/usr/bin/env python3
"""Build an ARM64 app image and deploy over SSH without copying runtime secrets."""
import argparse
from contextlib import suppress
from datetime import datetime, timezone
import hashlib
from pathlib import Path
import posixpath
import re
import shlex
import subprocess
import sys
import tarfile
import tempfile
import uuid

ROOT = Path(__file__).resolve().parents[1]


def run(command, **kwargs):
    display = list(command)
    if display[0] == 'ssh':
        display[-1] = '[remote command]'
    print('+ ' + shlex.join(str(part) for part in display), flush=True)
    return subprocess.run(command, check=True, **kwargs)


def preflight_script(args):
    checks = r'''set -eu
export PATH="$PATH:/usr/local/bin:/var/packages/ContainerManager/target/usr/bin:/var/packages/Docker/target/usr/bin"
check() {
    label=$1
    shift
    printf 'CHECK: %s\n' "$label"
    if "$@"; then
        printf 'OK: %s\n' "$label"
    else
        result=$?
        printf 'ERROR: %s (exit %s)\n' "$label" "$result" >&2
        exit "$result"
    fi
}
'''
    steps = [
        ('NAS deployment directory: ' + args.path, ['cd', args.path]),
        ('.env exists in ' + args.path + ' (prepare the NAS runtime .env first)', ['test', '-f', '.env']),
        ('.env readable by SSH user (check owner and permissions)', ['test', '-r', '.env']),
        ('Deployment directory writable by SSH user (needed for releases, backups and config)', ['test', '-w', '.']),
        ('sha256sum available on NAS', ['sh', '-c', 'command -v sha256sum >/dev/null']),
        ('tar available on NAS', ['sh', '-c', 'command -v tar >/dev/null']),
        ('Docker executable available on NAS', ['sh', '-c', 'command -v docker >/dev/null']),
    ]
    checks += '\n'.join('check ' + shlex.join([label] + command) for label, command in steps) + '\n'
    checks += 'docker_bin=$(command -v docker)\n'
    if not args.no_sudo:
        checks += 'check "sudo authentication for Docker" sudo -v\n'
    prefix = '' if args.no_sudo else 'sudo -n '
    checks += f'docker_info() {{ {prefix}"$docker_bin" info >/dev/null; }}\n'
    checks += 'check "Docker daemon access" docker_info\n'
    checks += f'check "Docker Compose plugin" {prefix}"$docker_bin" compose version\n'
    checks += 'printf "NAS preflight passed.\\n"\n'
    return checks


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--host', required=True, help='SSH config alias or user@NAS')
    parser.add_argument('--path', default='/volume1/oms/', help='Existing NAS deployment folder')
    parser.add_argument('--port', type=int, default=22)
    auth = parser.add_mutually_exclusive_group()
    auth.add_argument('--identity', type=Path, help='SSH private key file')
    auth.add_argument('--password', action='store_true', help='Use interactive SSH password authentication')
    parser.add_argument('--project', default='oms', help='Existing Compose project name; preserves volumes')
    parser.add_argument('--image', help='Unique image tag; generated by default (do not reuse deployed tags)')
    parser.add_argument('--skip-build', action='store_true', help='Use an existing local ARM64 image')
    parser.add_argument('--no-sudo', action='store_true', help='NAS user can run docker directly')
    parser.add_argument('--teams', action='store_true', help='Start Teams worker (requires NAS TEAMS_ENABLED=1)')
    parser.add_argument('--dry-run', action='store_true', help='Show plan without Docker, SSH or file changes')
    parser.add_argument('--check-only', action='store_true', help='Run labeled NAS checks without building or deploying')
    args = parser.parse_args(argv)
    if not re.fullmatch(r'[A-Za-z0-9_][A-Za-z0-9_.@-]*', args.host):
        parser.error('--host must be an SSH alias or user@hostname (use an alias for IPv6)')
    if not args.path.startswith('/') or any(c in args.path for c in '\n\r\0'):
        parser.error('--path must be an absolute NAS path without control characters')
    # Normalize NAS paths independently of the local operating system.
    args.path = posixpath.normpath('/' + args.path.lstrip('/'))
    if not re.fullmatch(r'[a-z0-9][a-z0-9_-]*', args.project):
        parser.error('--project must use lowercase letters, digits, underscores or hyphens')
    if not 1 <= args.port <= 65535:
        parser.error('--port must be between 1 and 65535')
    if args.skip_build and not args.image:
        parser.error('--skip-build requires --image')
    if args.image and (not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9._:/-]*', args.image)
                       or ':' not in args.image.rsplit('/', 1)[-1]
                       or args.image.endswith(':latest')):
        parser.error('--image must have an explicit release tag other than latest')
    return args


def deploy(args, control_path):
    release = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ') + '-' + uuid.uuid4().hex[:8]
    image = args.image or 'oms:' + release
    remote_release = args.path.rstrip('/') + '/releases/' + release
    ssh = ['ssh', '-o', 'BatchMode=no', '-o', 'ConnectTimeout=15',
           '-o', 'ControlMaster=auto', '-o', 'ControlPersist=600',
           '-o', 'ControlPath=' + str(control_path), '-p', str(args.port)]
    if args.identity:
        ssh += ['-i', str(args.identity.expanduser())]
    if args.password:
        ssh += ['-o', 'PubkeyAuthentication=no', '-o', 'PreferredAuthentications=keyboard-interactive,password']
    docker = 'docker' if args.no_sudo else 'sudo'
    print(f'Target: {args.host}:{args.path}; project={args.project}; image={image}', flush=True)
    if args.dry_run:
        print('Plan: SSH preflight → ARM64 build/inspect → save/checksum → SSH transfer')
        print('NAS: lock → verify/load → config/security checks → stop writers → DB/media backups')
        print('NAS: migrate → start app/worker/tunnel → health checks → persist image tag')
        print('Runtime .env and secrets stay on NAS. Artifacts: dist/nas/<release>/')
        return 0

    # Fail before building/transferring if SSH, permissions or sudo are unavailable.
    preflight = preflight_script(args)
    # A real remote TTY lets sudo prompt securely; subsequent Docker calls use its cache.
    run(ssh + ['-tt', args.host, 'sh -c ' + shlex.quote(preflight)])
    if args.check_only:
        return 0
    if not args.skip_build:
        run(['docker', 'buildx', 'build', '--platform', 'linux/arm64', '--load', '-t', image, '.'], cwd=ROOT)
    architecture = subprocess.check_output(
        ['docker', 'image', 'inspect', image, '--format', '{{.Os}}/{{.Architecture}}'], text=True).strip()
    if architecture != 'linux/arm64':
        raise RuntimeError(f'Expected linux/arm64 image; got {architecture}')
    image_id = subprocess.check_output(
        ['docker', 'image', 'inspect', image, '--format', '{{.Id}}'], text=True).strip()
    stage = ROOT / 'dist' / 'nas' / release
    stage.mkdir(parents=True)
    run(['docker', 'save', '-o', str(stage / 'app-image.tar'), image])
    for source in [ROOT / 'compose.cloudflare.yaml', ROOT / 'scripts' / 'deploy_nas_remote.sh']:
        (stage / source.name).write_bytes(source.read_bytes())
    (stage / 'image-id').write_text(image_id + '\n')
    checksums = []
    for path in sorted(stage.iterdir()):
        digest = hashlib.sha256()
        with path.open('rb') as stream:
            for chunk in iter(lambda: stream.read(1024 * 1024), b''):
                digest.update(chunk)
        checksums.append(f'{digest.hexdigest()}  {path.name}')
    (stage / 'SHA256SUMS').write_text('\n'.join(checksums) + '\n')
    payload = stage / 'payload.tar'
    with tarfile.open(payload, 'w') as archive:
        for path in sorted(stage.iterdir()):
            if path != payload:
                archive.add(path, arcname=path.name)
    receive = 'umask 077; mkdir -p ' + shlex.quote(remote_release) + ' && tar -xf - -C ' + shlex.quote(remote_release)
    with payload.open('rb') as stream:
        # Never allocate a TTY for binary transfers, including with RequestTTY in ssh_config.
        run(ssh + ['-T', args.host, 'sh -c ' + shlex.quote(receive)], stdin=stream)
    command = shlex.join(['sh', remote_release + '/deploy_nas_remote.sh',
                          args.path, remote_release, args.project, image, docker,
                          '1' if args.teams else '0'])
    run(ssh + ['-tt', args.host, command])
    payload.unlink()
    print(f'Deployment complete. Local artifacts: {stage}')
    return 0


def main(argv=None):
    args = parse_args(argv)
    if args.dry_run:
        return deploy(args, '<private-control-socket>')
    # A short private path also fits macOS's Unix socket path limit.
    with tempfile.TemporaryDirectory(prefix='oms-ssh-', dir='/tmp') as folder:
        control = Path(folder) / 'control'
        try:
            return deploy(args, control)
        finally:
            # Close the shared authenticated connection on success, failure or Ctrl-C.
            with suppress(OSError, subprocess.TimeoutExpired):
                subprocess.run(['ssh', '-S', str(control), '-O', 'exit', args.host],
                               stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                               stderr=subprocess.DEVNULL, timeout=15, check=False)


if __name__ == '__main__':
    try:
        sys.exit(main())
    except subprocess.CalledProcessError as error:
        print(f'Deployment failed (exit {error.returncode}). See the CHECK/ERROR output above.', file=sys.stderr)
        sys.exit(1)
    except (OSError, RuntimeError) as error:
        print(f'Deployment failed: {error}', file=sys.stderr)
        sys.exit(1)
    except KeyboardInterrupt:
        print('Deployment interrupted.', file=sys.stderr)
        sys.exit(130)
